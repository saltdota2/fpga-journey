"""Generate coefficients, input samples and the bit-exact expected output for rtl/fir_lp.sv.

Reference arithmetic (see the task):
  y[n] = saturate_16( (sum_{k=0..30} COEFF[k] * x[n-k] + 2^14) >> 15 ),  x[m] = 0 before the first sample
"""
import numpy as np
from scipy.signal import firwin

FS = 8000
TAPS = 31
CUTOFF = 1000
N = 4000
SEED = 11

# ---- coefficients ----
h = firwin(TAPS, CUTOFF, fs=FS)
hq = np.round(h * 2**15).astype(int)            # Q1.15
assert np.array_equal(hq, hq[::-1])

with open("rtl/fir_lp_coeffs.svh", "w") as f:
    vals = ",\n    ".join(", ".join(f"16'sd{v}" if v >= 0 else f"-16'sd{-v}" for v in hq[i:i+8])
                         for i in range(0, TAPS, 8))
    f.write("// Generated by model/fir_vectors.py - do not edit by hand\n")
    f.write(f"// {TAPS}-tap low-pass FIR, cutoff {CUTOFF} Hz at fs = {FS} Hz, coefficients in Q1.15\n")
    f.write("// y[n] = sum over k = 0..30 of COEFF[k] * x[n-k]\n")
    f.write(f"localparam logic signed [15:0] COEFF [{TAPS}] = '{{\n    {vals}\n}};\n")

# ---- input signal: "station" 200 Hz + interference 2500 Hz + noise ----
rng = np.random.default_rng(SEED)
t = np.arange(N) / FS
x = 0.5 * np.sin(2 * np.pi * 200 * t) + 0.3 * np.sin(2 * np.pi * 2500 * t) \
    + 0.05 * rng.standard_normal(N)
xq = np.clip(np.round(x * 2**15), -32768, 32767).astype(int)

# ---- bit-exact model of the hardware ----
def fir_bitexact(xq):
    line = np.zeros(TAPS, dtype=np.int64)       # line[k] = x[n-k]
    out = []
    for sample in xq:
        line = np.roll(line, 1)
        line[0] = sample
        acc = int(np.dot(hq.astype(np.int64), line))   # exact, no intermediate rounding
        r = (acc + (1 << 14)) >> 15             # round half up, drop 15 bits
        out.append(max(-32768, min(32767, r)))  # saturate to 16 bit
    return np.array(out)

yq = fir_bitexact(xq)

def write_hex(name, arr):
    with open(name, "w") as f:
        for v in arr:
            f.write(f"{int(v) & 0xFFFF:04x}\n")

write_hex("data/fir_in.hex", xq)
write_hex("data/fir_expected.hex", yq)
np.save("data/fir_in.npy", xq)
np.save("data/fir_expected.npy", yq)
print("coeffs:", list(hq))
print("max |out| =", abs(yq).max())
